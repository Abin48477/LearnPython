# it is use to skip the current iteration.for example:
developer_name =['abin','prabin','sasin','ashok']

for dn in developer_name:
    if dn == 'prabin':
        continue
    print(dn)

developer_names = ['Jess', 'Naomi', 'Tom']

for developer in developer_names:
    if developer == 'Naomi':
        continue
    print(developer)